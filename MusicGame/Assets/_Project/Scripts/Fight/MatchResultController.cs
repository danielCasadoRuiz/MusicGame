using TMPro;
using UnityEngine;
using UnityEngine.UI;

/// <summary>
/// The real post-Fight result screen — ONE configurable MatchResultView representing both Win and
/// Lose (see that class's own doc), never two parallel screens. Shown for FightFlowState.MatchWon/
/// MatchLost; FightMatchController already decided everything shown here — rounds / reason / health% via
/// MatchEndedEvent (cached the instant it arrives, same _pendingData pattern as RoundEndController) and the
/// campaign outcome via CampaignService.LastCombat — this class only presents it and reacts to the
/// player's own choice. ONE results list, three labelled sections (see PopulateResults):
///   FIGHT  the fight just decided: won / lost vs whom, its stars, rounds, how it ended, its metrics
///   RACE   the run that led to this fight (its stars + score) — real values on a loss too
///   MATCH  the whole match (race + fight): combined stars on a win and its effect on the campaign level
///          (position completed / next position / level or lap completed / improved record / new card);
///          on a loss: "not passed" and the extra lives left for Fight Again.
///
/// Actions:
///
///   WIN  -> Continue: hands off entirely to NextSongTransitionController (see its own doc) — this
///           class never touches song selection/loading itself.
///   LOSE -> Fight Again (PlayerProgressService.ExtraLives > 0, persistent): consumes one life, restarts the
///           SAME match (same GameSession.SelectedOpponent/SelectedOpponentLevelConfig/
///           SelectedOpponentSong — never re-runs Opponent Selection) via FightFlowState.VersusIntro,
///           exactly the "Fight Again -> VS curt -> Round 1 -> Countdown -> Fight" sequence the task
///           asked for (FightMatchController.BeginMatch/VersusScreenController's own existing
///           sequencing does the rest, unchanged).
///        -> Fight Again (no lives): opens the Rewarded Ad confirmation sub-panel instead (see
///           IRewardedAdService's own doc) — Watch Ad grants +1 life and immediately starts Fight
///           Again on success; Cancel returns to this same Lose screen.
///        -> Replay Song: the SAME match from its start, through the normal full flow — Runner (new run
///           session) → race results → Fight (roulette reveal of the SAME assigned rival → versus →
///           rounds) → this screen. The persisted assignment (song + rival + campaign position + runner
///           difficulty) is re-applied first (RunAssignment.TryRestorePending, exactly what CONTINUE does),
///           then GameFlowState.Gameplay is requested (the song's analysis is already in GameSession — see
///           OnReplaySongClicked). Nothing is duplicated: records keep only the best, lives are granted once
///           per match (RunRewardRules), the specials wallet starts empty. Does NOT consume a life.
///   BOTH -> Main Menu: unchanged.
///
/// The composer's last words are NOT here: they play in the arena before this screen opens
/// (FightFlowState.MatchFarewell, MatchFarewellController). On arrival every button stays inert for
/// one frame, so the press that skipped the farewell can never also activate a result button.
///
/// The whole screen (reward-ad modal and evaluation panel included) is the MatchResult.prefab instance
/// spawned from UIPrefabLibrarySO.matchResult (generated by Tools > MusicGame > UI > Build All UI
/// Prefabs, then edited by hand) — no UI is built in code; a missing prefab logs an error and disables
/// this controller.
///
/// Lives in the always-loaded UI Scene (added by UIFlowController) — reacts to
/// FightFlowStateChangedEvent directly.
/// </summary>
public class MatchResultController : MonoBehaviour
{
    private MatchResultView _view;   // the spawned MatchResult.prefab instance
    private RectTransform   _root;
    private TextMeshProUGUI _titleText;
    private TextMeshProUGUI _perfectBanner;
    private Coroutine       _perfectRoutine;

    private Button          _continueButton;
    private Button          _selectSongButton; // won match only: choose the next song manually (secondary to CONTINUE)
    private Button          _fightAgainButton;
    private TextMeshProUGUI _fightAgainButtonLabel;
    private Button          _replaySongButton;
    private Button          _mainMenuButton;

    private GameObject _rewardAdModalRoot;

    private readonly IRewardedAdService _adService = new NotImplementedRewardedAdService();

    private MatchEndedEvent? _pendingMatchEnded;
    // SELECT SONG: what this screen showed, kept to re-present it unchanged when Song Selection's BACK returns
    // here (MatchResultReturn) — presentation only, nothing is re-evaluated or re-awarded.
    private MatchEndedEvent? _returnMatchEnded;
    private RivalVersionUnlockedEvent? _returnUnlock, _shownUnlock;
    private System.Action<FightFlowStateChangedEvent> _onFightFlowChanged;
    private System.Action<MatchEndedEvent> _onMatchEnded;
    private System.Action<GameFlowStateChangedEvent> _onGameFlowChanged;

    /// <summary>Set only while Replay Song is waiting for Runner to actually be ready — see
    /// OnReplaySongClicked's own doc. Lets _onGameStarted below tell "a real Replay Song transition
    /// finished" apart from GameStartedEvent firing for any unrelated reason.</summary>
    private bool _awaitingReplaySongReady;
    private System.Action<GameStartedEvent> _onGameStarted;
    // First-time defeat of a rival version (PlayerProgressService) — published by FightMatchController
    // BEFORE MatchWon, shown once on this result screen, then cleared.
    private RivalVersionUnlockedEvent? _pendingUnlock;
    private System.Action<RivalVersionUnlockedEvent> _onRivalUnlocked;

    private EvaluationPanel _evalPanel;   // the ONE results list (FIGHT / RACE / MATCH)
    private bool _inputGuard;              // true for the screen's first frame (see class doc)
    private bool _replaySongLocksButtons;  // true while Replay Song waits for Runner (see OnReplaySongClicked)
    private Coroutine _unblockRoutine;

    private void Awake()
    {
        var lib = UIPrefabLibrarySO.Instance;
        _view = UIPrefabLibrarySO.Spawn(lib != null ? lib.matchResult : null, UIFactory.RootCanvas(), "MatchResult");
        if (_view == null) { enabled = false; return; } // Spawn already logged the error
        _view.name = "MatchResultScreen";
        WireUI(_view);
        UIFactory.Stretch(_root);
        // Nested in the prefab; a MatchResult.prefab generated before that still gets the library's panel.
        if (_evalPanel == null) _evalPanel = EvaluationPanel.Spawn(_root, "Evaluation"); // anchoring/size from the prefab

        _root.gameObject.SetActive(false);
    }

    private void OnDestroy()
    {
        if (_view != null) Destroy(_view.gameObject);
    }

    private void OnEnable()
    {
        // Cached the instant it arrives — FightMatchController publishes MatchEndedEvent BEFORE
        // requesting FightFlowState.MatchWon/MatchLost (see its own NotifyRoundEndDisplayComplete),
        // so this data is always ready by the time Show() below actually runs.
        _onMatchEnded = e => { _pendingMatchEnded = e; _returnMatchEnded = null; _returnUnlock = null; }; // a real new result
        _onFightFlowChanged = e =>
        {
            if (e.Current == FightFlowState.MatchWon)
            {
                // Back from Song Selection (FightFlowController resumed straight at MatchWon): the same result.
                if (_returnMatchEnded.HasValue && e.Previous == FightFlowState.MatchWon)
                {
                    _pendingMatchEnded = _returnMatchEnded;
                    _pendingUnlock     = _returnUnlock;
                    _returnMatchEnded  = null;
                    _returnUnlock      = null;
                    FightMusicController.Instance?.Lock(GameSession.Instance?.SelectedOpponentSong, GameSession.Instance?.SelectedOpponentLevelConfig);
                }
                Show(true);
            }
            else if (e.Current == FightFlowState.MatchLost) Show(false);
            // A fresh match starting over (see FightFlowController's own re-entry announcement) —
            // clean up so a stale result never lingers behind the next Opponent Selection.
            else if (e.Current == FightFlowState.OpponentSelection) ExitFightUI();
        };
        // See OnReplaySongClicked's own doc — this is the REAL "Runner is fully ready" signal
        // (GameplayManager only publishes it once the level is generated AND the player/camera are
        // already placed), the exact same one AnalyzingScreenController already uses to hide its own
        // full-screen cover after a scene transition into Gameplay. _awaitingReplaySongReady gates
        // this so an unrelated GameStartedEvent (e.g. a later real Gameplay entry) never hides this
        // screen by accident.
        _onGameStarted = _ =>
        {
            if (!_awaitingReplaySongReady) return;
            _awaitingReplaySongReady = false;
            Hide();
            SetReplaySongButtonsInteractable(true);
        };
        // Top-level safety net — every other Fight-exclusive screen gets the exact same one (see
        // VersusScreenController.OnEnable's own doc): FightFlowStateChangedEvent alone freezes the
        // instant top-level GameFlowState leaves Fight (FightFlowController stops publishing), so
        // without this, a result screen left showing at MatchWon/MatchLost (e.g. Main Menu clicked)
        // would stay active forever — exactly the reported "Match Result still up under Runner's
        // countdown" bug. The ONE exception: while _awaitingReplaySongReady is true, this screen IS
        // the intended cover for that specific transition (see OnReplaySongClicked's own doc) — the
        // very same GameFlowStateChangedEvent that fires here (Previous == Fight, on the Replay Song
        // click itself) is what starts that transition, so skipping cleanup in that one case is what
        // keeps Replay Song's fix intact; _onGameStarted above still guarantees it gets cleaned up
        // for real the moment Runner is actually ready.
        _onGameFlowChanged = e =>
        {
            // Replay Song whose Runner could not start (the barrier failed and went back to Song Selection):
            // no GameStartedEvent will come — release this cover instead of waiting for it forever.
            if (_awaitingReplaySongReady && e.Previous == GameFlowState.Gameplay && e.Current != GameFlowState.Gameplay)
            {
                _awaitingReplaySongReady = false;
                SetReplaySongButtonsInteractable(true);
                ExitFightUI();
                return;
            }
            if (e.Previous != GameFlowState.Fight) return;
            if (_awaitingReplaySongReady) return;
            ExitFightUI();
        };
        _onRivalUnlocked = e => _pendingUnlock = e;
        EventBus.Subscribe(_onRivalUnlocked);
        EventBus.Subscribe(_onMatchEnded);
        EventBus.Subscribe(_onFightFlowChanged);
        EventBus.Subscribe(_onGameStarted);
        EventBus.Subscribe(_onGameFlowChanged);
    }

    private void OnDisable()
    {
        EventBus.Unsubscribe(_onRivalUnlocked);
        EventBus.Unsubscribe(_onMatchEnded);
        EventBus.Unsubscribe(_onFightFlowChanged);
        EventBus.Unsubscribe(_onGameStarted);
        EventBus.Unsubscribe(_onGameFlowChanged);
        EndInputGuard();
    }

    /// <summary>The one real cleanup point for this screen when Fight itself is genuinely being left
    /// behind (as opposed to mid-Replay-Song-transition — see OnEnable's own doc) — hides the root,
    /// closes the reward-ad sub-panel, re-enables every button, and drops the cached match data so a
    /// stale MatchEndedEvent can never leak into a later Show(). Also reachable via the normal
    /// FightFlowState.OpponentSelection re-entry hide (a fresh match starting over within the SAME
    /// Fight session) — this is the stronger, top-level version of that same idea.</summary>
    private void ExitFightUI()
    {
        Hide();
        HideRewardAdModal();
        SetReplaySongButtonsInteractable(true);
        _awaitingReplaySongReady = false;
        _pendingMatchEnded = null;
    }

    // ── Prefab wiring — see MatchResultView's own doc ────────────────────────────

    private void WireUI(MatchResultView view)
    {
        _root        = view.root != null ? view.root.GetComponent<RectTransform>() : (RectTransform)view.transform;
        _titleText   = view.titleText;
        _perfectBanner = view.perfectBanner;

        _continueButton = view.continueButton;
        view.continueButton.onClick.AddListener(OnContinueClicked);

        _selectSongButton = view.selectSongButton;
        if (_selectSongButton != null) _selectSongButton.onClick.AddListener(OnSelectSongClicked);

        _fightAgainButton = view.fightAgainButton;
        _fightAgainButtonLabel = view.fightAgainButtonLabel;
        view.fightAgainButton.onClick.AddListener(OnFightAgainClicked);

        _replaySongButton = view.replaySongButton;
        view.replaySongButton.onClick.AddListener(OnReplaySongClicked);

        _mainMenuButton = view.mainMenuButton;
        view.mainMenuButton.onClick.AddListener(OnMainMenuClicked);

        _rewardAdModalRoot = view.rewardAdModalRoot;
        view.watchAdButton.onClick.AddListener(OnWatchAdClicked);
        view.cancelButton.onClick.AddListener(OnCancelAdClicked);
        _rewardAdModalRoot.SetActive(false);

        _evalPanel = view.evaluationPanel;
    }

    // ── Show / hide ───────────────────────────────────────────────────────────────

    private void Show(bool playerWon)
    {
        var data = _pendingMatchEnded ?? default;

        // A fresh result screen always starts from a clean slate — in particular this cancels any
        // Replay Song wait left over from a PREVIOUS match's screen (should never happen in practice,
        // since OpponentSelection already hides this screen first, but never leave buttons disabled
        // or a stale subscription gate armed either way).
        _awaitingReplaySongReady = false;
        SetReplaySongButtonsInteractable(true);

        bool boss = GameSession.Instance != null && GameSession.Instance.CurrentBossStage >= 0;
        // The title is the MATCH outcome (a final-rival stage has no race: its title is the fight's).
        Loc.Set(_titleText, boss ? (playerWon ? "Fight.YouWin" : "Fight.YouLose")
                                 : (playerWon ? "Results.MatchPassed" : "Results.MatchNotPassed"));
        _continueButton.gameObject.SetActive(playerWon);
        // Final-rival stages are combat-only: no song to choose or replay.
        if (_selectSongButton != null) _selectSongButton.gameObject.SetActive(playerWon && !boss);
        _fightAgainButton.gameObject.SetActive(!playerWon);
        _replaySongButton.gameObject.SetActive(!playerWon && !boss);
        if (!playerWon) RefreshFightAgainLabel();

        HideRewardAdModal();
        _root.gameObject.SetActive(true);
        _root.SetAsLastSibling();

        PopulateResults(playerWon, data);
        ShowPerfect(false);
        _shownUnlock   = _pendingUnlock;
        _pendingUnlock = null; // shown once; a repeat victory over the same version never sets it
        BeginInputGuard();
    }

    // ── The ONE results list: FIGHT / RACE / MATCH ─────────────────────────────

    private void PopulateResults(bool playerWon, MatchEndedEvent data)
    {
        if (_evalPanel == null) return;
        _evalPanel.Clear();
        _evalPanel.gameObject.SetActive(true);
        var c = CampaignService.LastCombat;
        var p = _evalPanel;

        // FIGHT — the fight just decided.
        p.AddHeader(Loc.Get(playerWon ? "Results.FightWon" : "Results.FightLost", OpponentDisplayName(), RivalVersion()));
        if (c != null)
            p.AddStars(Loc.Get("Results.FightStars") + (c.Evaluation.Perfect ? "  " + Loc.Get("Eval.Perfect") : "") +
                       (playerWon && !c.Boss && c.Record.NewRecord ? "  " + Loc.Get("Eval.NewRecord") : ""), c.Evaluation.HalfStars);
        p.AddLine(FightLine(data));
        if (c != null) p.AddNote(EvaluationPanel.Breakdown(c.Evaluation.Metrics));

        if (c != null && c.Boss) { BossSection(c, playerWon); return; }

        // RACE — the run that led to this fight (its real values, also on a loss).
        var race = c != null ? (c.RunnerOfThisMatch ?? (!c.Recorded ? CampaignService.LastRunner : null)) : CampaignService.LastRunner;
        if (race != null)
        {
            p.AddHeader(Loc.Get("Results.RaceHeader", SongDisplayName()));
            p.AddStars(Loc.Get("Results.RaceStars"), race.Evaluation.HalfStars);
            p.AddNote(Loc.Get("Results.Score", race.GameScore.ToString("N0"), race.GameMaxScore.ToString("N0"),
                              Mathf.RoundToInt(Mathf.Clamp01(race.GameNormalized) * 100f).ToString()) +
                      "  ·  " + Loc.Get("Eval.Falls", race.Falls.ToString()));
        }

        // MATCH — race + fight together, and what it did to the campaign level.
        var position = c != null && c.Recorded && CampaignService.Available ? CampaignModel.Find(CampaignService.Data, c.PositionId) : null;
        string where = position != null ? CampaignService.PositionLabel(position.levelId, position.matchNumber) : "";
        p.AddHeader(string.IsNullOrEmpty(where) ? Loc.Get("Results.MatchHeaderFree") : Loc.Get("Results.MatchHeader", where));
        if (!playerWon)
        {
            p.AddWarning(Loc.Get("Results.NotPassed"));
            p.AddNote(Loc.Get("Results.LivesLeft", ExtraLives.ToString()));
            return;
        }
        if (race != null && c != null)
            p.AddStars(Loc.Get("Results.MatchStars"), StarMath.Combine(race.Evaluation.HalfStars, c.Evaluation.HalfStars));
        if (position == null) { p.AddNote(Loc.Get("Eval.NotCampaign")); AddUnlock(p); return; }

        var advance = c.Advance;
        if (!string.IsNullOrEmpty(advance.CompletedPositionId))
        {
            if (advance.LapCompleted) p.AddHighlight(Loc.Get("Eval.LapCompleted"));
            else if (advance.LevelCompleted) p.AddHighlight(Loc.Get("Results.LevelCompletedNext", CampaignService.CurrentPositionLabel));
            else p.AddHighlight(Loc.Get("Results.Advanced", CampaignService.CurrentPositionLabel));
        }
        else p.AddNote(Loc.Get("Results.ReplayedPosition")); // an earlier position: records only, no advance

        bool improved = c.Record.NewRecord || (race != null && race.Recorded && race.Record.NewRecord);
        p.AddStarsSmall(Loc.Get(improved ? "Results.RecordImproved" : "Results.RecordKept"), CampaignModel.CombinedHalfStars(position));
        if (c.Record.JustMastered || (race != null && race.Recorded && race.Record.JustMastered)) p.AddHighlight(Loc.Get("Eval.JustMastered"));
        AddUnlock(p);
    }

    private void AddUnlock(EvaluationPanel p)
    {
        if (!_pendingUnlock.HasValue || _pendingUnlock.Value.Opponent == null) return;
        var u = _pendingUnlock.Value;
        p.AddHighlight(Loc.Get("MatchResult.NewRival") + " — " + Loc.Get("MatchResult.NewRivalLevel", u.Opponent.displayName, u.Level.ToString()));
    }

    // Final-rival stage: no race; the stage record and the challenge's progress are the "match".
    private void BossSection(CombatPhaseOutcome c, bool playerWon)
    {
        var p = _evalPanel;
        p.AddHeader(Loc.Get("Eval.BossStage", (c.BossStage + 1).ToString()));
        if (c.BossBest != null && c.BossBest.has && c.BossBest.valid)
            p.AddStarsSmall(Loc.Get("Eval.BestOfStage") + (c.BossNewRecord ? "  " + Loc.Get("Eval.NewRecord") : ""), c.BossBest.halfStars);
        if (!playerWon) { p.AddWarning(Loc.Get("Eval.LossInformative")); p.AddNote(Loc.Get("Results.LivesLeft", ExtraLives.ToString())); return; }
        if (c.BossNextStageAvailable) p.AddHighlight(Loc.Get("Eval.BossNext", (c.BossStage + 2).ToString()));
        if (c.BossSequenceCompleted) p.AddHighlight(Loc.Get("Eval.BossDefeated"));
        if (CampaignService.Available && CampaignService.Data.boss.sealGranted && !CampaignService.Data.boss.sealCelebrationShown)
            p.AddHighlight(Loc.Get("Campaign.SealName"));
        AddUnlock(p);
    }

    // PERFECT is announced per ROUND (FightController: a KO round won with a full bar), never at the end of the match.
    private void ShowPerfect(bool show)
    {
        if (_perfectBanner != null) _perfectBanner.gameObject.SetActive(false);
    }

    private void Hide()
    {
        EndInputGuard();
        ShowPerfect(false);
        _root.gameObject.SetActive(false);
    }

    // ── One-frame input guard ────────────────────────────────────────────────────

    private void BeginInputGuard()
    {
        if (_unblockRoutine != null) StopCoroutine(_unblockRoutine);
        _inputGuard = true;
        ApplyButtonsInteractable();
        _unblockRoutine = isActiveAndEnabled ? StartCoroutine(UnblockNextFrame()) : null;
        if (_unblockRoutine == null) EndInputGuard();
    }

    private System.Collections.IEnumerator UnblockNextFrame()
    {
        yield return null;
        _unblockRoutine = null;
        if (UnityEngine.EventSystems.EventSystem.current != null)
            UnityEngine.EventSystems.EventSystem.current.SetSelectedGameObject(null);
        EndInputGuard();
    }

    private void EndInputGuard()
    {
        if (_unblockRoutine != null) { StopCoroutine(_unblockRoutine); _unblockRoutine = null; }
        _inputGuard = false;
        ApplyButtonsInteractable();
    }

    private void ApplyButtonsInteractable()
    {
        bool free = !_inputGuard;
        bool freeOfReplay = free && !_replaySongLocksButtons;
        if (_continueButton != null)   _continueButton.interactable   = free;
        if (_selectSongButton != null) _selectSongButton.interactable = free;
        if (_fightAgainButton != null) _fightAgainButton.interactable = freeOfReplay;
        if (_replaySongButton != null) _replaySongButton.interactable = freeOfReplay;
        if (_mainMenuButton != null)   _mainMenuButton.interactable   = freeOfReplay;
    }

    /// <summary>Disables Fight Again/Replay Song/Main Menu the instant Replay Song is clicked (see
    /// its own doc — prevents a double-click firing a second scene transition while the first is
    /// still loading underneath this still-visible screen), re-enabled once it's actually hidden
    /// again (either by GameStartedEvent completing the transition, or by Show() starting a fresh
    /// result screen).</summary>
    private void SetReplaySongButtonsInteractable(bool interactable)
    {
        _replaySongLocksButtons = !interactable;
        ApplyButtonsInteractable(); // also respects a composer line still on screen
    }

    private void RefreshFightAgainLabel()
    {
        int lives = ExtraLives;
        _fightAgainButtonLabel.text = lives > 0
            ? Loc.Get("MatchResult.FightAgainCount", lives.ToString())
            : Loc.Get("MatchResult.FightAgain");
    }

    // The persistent life inventory — the same counter the Runner HUD/summary show.
    private static int ExtraLives => PlayerProgressService.Instance != null ? PlayerProgressService.Instance.ExtraLives : 0;

    // "Rounds 2–1 · KO · Health: you 64% / rival 0%" (+ "wins on points" when the tie-break decided it).
    // The round scoreboard always stays honest about what happened round by round — a points/fallback
    // decision is only ever surfaced as its own clause, never as a faked round win.
    private static string FightLine(MatchEndedEvent data)
    {
        string reason  = Loc.Get(data.LastRoundReason == RoundEndReason.KO ? "Fight.KO" : "Fight.TimeUp");
        int playerHp   = Mathf.RoundToInt(data.PlayerHealthPercent * 100f);
        int opponentHp = Mathf.RoundToInt(data.OpponentHealthPercent * 100f);
        string line = Loc.Get("Results.Rounds", data.PlayerRoundsWon.ToString(), data.OpponentRoundsWon.ToString()) + "  ·  " + reason +
                      "  ·  " + Loc.Get("MatchResult.FinalHealth", playerHp.ToString(), opponentHp.ToString());
        if (data.Resolution == MatchResolution.PointsTiebreak || data.Resolution == MatchResolution.ExactTieFallback)
        {
            string winnerName = data.Winner == FighterSide.Player ? Loc.Get("Fight.PlayerName") : OpponentDisplayName();
            line += "  ·  " + Loc.Get("Fight.WinsOnPoints", winnerName);
        }
        return line;
    }

    private static string RivalVersion()
    {
        var level = GameSession.Instance != null ? GameSession.Instance.SelectedOpponentLevelConfig : null;
        return level != null ? level.level.ToString() : "?";
    }

    private static string SongDisplayName()
    {
        var song = GameSession.Instance != null ? GameSession.Instance.SelectedSong : null;
        return song.HasValue ? song.Value.DisplayName : "";
    }

    private static string OpponentDisplayName() =>
        GameSession.Instance?.SelectedOpponent != null
            ? GameSession.Instance.SelectedOpponent.displayName
            : Loc.Get("Fight.RivalUnknown");

    // ── Button handlers ───────────────────────────────────────────────────────────

    private void OnContinueClicked()
    {
        // Final rival: next stage right here (same Fight scene, new version / song / arena), or back to the
        // Main Menu after the last one (the finale is shown there).
        var lastCombat = CampaignService.LastCombat;
        if (lastCombat != null && lastCombat.Boss)
        {
            Hide();
            if (lastCombat.BossNextStageAvailable && CampaignService.PrepareBossStage(lastCombat.BossStage + 1))
            {
                FightMusicController.Instance?.Lock(GameSession.Instance.SelectedOpponentSong, null);
                FightFlowController.Instance?.RequestState(FightFlowState.VersusIntro);
            }
            else
            {
                FightMusicController.Instance?.Stop();
                AppBootstrap.Context?.AppFlow.RequestState(GameFlowState.MainMenu);
            }
            return;
        }
        // Lap just finished: the Main Menu celebrates it / offers a new lap.
        if (CampaignService.LapFinished)
        {
            Hide();
            FightMusicController.Instance?.Stop();
            AppBootstrap.Context?.AppFlow.RequestState(GameFlowState.MainMenu);
            return;
        }
        Hide();
        NextSongTransitionController.Instance?.BeginWin();
    }

    // SELECT SONG (won match): the existing selector instead of the automatic route pick. Confirming a
    // song there makes it the new seed and creates its pendingRun (same CreatePendingRun pipeline as
    // CONTINUE); completed songs are shown but disabled. The defended song is already completed and
    // its pendingRun already cleared (FightMatchController), so nothing is abandoned here.
    private void OnSelectSongClicked()
    {
        _returnMatchEnded = _pendingMatchEnded;
        _returnUnlock     = _shownUnlock;
        MatchResultReturn.Arm(); // Song Selection's BACK returns to this result
        Hide();
        FightMusicController.Instance?.Stop();
        AppBootstrap.Context?.AppFlow.RequestState(GameFlowState.SongSelection);
    }

    private void OnFightAgainClicked()
    {
        if (ExtraLives > 0) BeginFightAgain();
        else ShowRewardAdModal();
    }

    private void BeginFightAgain()
    {
        // Consumes (and saves) one persistent extra life; the normal first attempt never costs one.
        if (PlayerProgressService.Instance == null || !PlayerProgressService.Instance.TryConsumeLife()) return;
        Hide();
        // Same rival/level/song as before — no Opponent Selection re-run (task's own explicit
        // requirement). FightMusicController.Lock is a no-op while this opponent's playlist is
        // already playing, so the music simply carries on into the rematch.
        FightMusicController.Instance?.Lock(GameSession.Instance?.SelectedOpponentSong, GameSession.Instance?.SelectedOpponentLevelConfig);
        FightFlowController.Instance?.RequestState(FightFlowState.VersusIntro);
    }

    /// <summary>
    /// Requests GameFlowState.Gameplay DIRECTLY — SongAnalysis is never requested here (unchanged;
    /// see class doc). GameSession.SelectedSong/Profile already hold the exact song + analysis that
    /// led to this Fight (nothing overwrites them during a Fight session), so SceneFlowController.
    /// LoadMode(Runner) loads a completely FRESH Runner.unity, whose own RunnerSceneBootstrap.
    /// OnEnable() re-applies GameSession.SelectedSong.Clip and re-publishes GameSession.Profile via
    /// SongProfileReadyEvent — the EXACT same bootstrap a normal Song Selection -> Play entry uses,
    /// never duplicated here. A genuinely new run of the same, already-analyzed song. Does NOT
    /// consume a life.
    ///
    /// VISUAL: this path skips SongAnalysis/AnalyzingScreen — which is exactly what leaves it with no
    /// full-screen cover of its own for the async Runner scene load, unlike a normal Play entry
    /// (AnalyzingScreenController's own doc explains it stays up through that entire gap for THAT
    /// path). Hiding this screen immediately here would expose several raw frames of the Fight arena/
    /// stripped HUD/badly-placed camera underneath while Runner loads — so instead THIS screen stays
    /// fully visible and becomes the cover for that gap: buttons are disabled (no double-click
    /// firing a second transition) and Hide() is deferred to _onGameStarted, the same real "Runner is
    /// fully ready" signal (GameStartedEvent — GameplayManager only publishes it once the level is
    /// generated AND the player/camera are correctly placed) AnalyzingScreenController already
    /// reuses for this exact purpose — never an arbitrary WaitForSeconds timer.
    /// </summary>
    private void OnReplaySongClicked()
    {
        if (_awaitingReplaySongReady) return; // already in flight — ignore a stray extra click
        Debug.Log("[MatchResultController] Replay Song clicked -> same match from the start (assignment re-applied), requesting GameFlowState.Gameplay; this screen stays visible until GameStartedEvent.");
        ReapplyAssignment();

        SetReplaySongButtonsInteractable(false);
        _awaitingReplaySongReady = true;
        FightMusicController.Instance?.Stop();
        AppBootstrap.Context?.AppFlow.RequestState(GameFlowState.Gameplay);
    }

    /// <summary>Replay = the SAME persisted match again: re-applies its song + rival + campaign position +
    /// runner difficulty exactly as CONTINUE does (RunAssignment.TryRestorePending), so the replayed run and
    /// the fight after it are the normal flow of that match — never a stale or different setup. A local-file
    /// run (no assignment) simply keeps its session rival.</summary>
    private static void ReapplyAssignment()
    {
        var progress = PlayerProgressService.Instance;
        var song = GameSession.Instance != null ? GameSession.Instance.SelectedSong : null;
        if (progress == null || !song.HasValue || string.IsNullOrEmpty(song.Value.SongId) || !progress.IsPendingSong(song.Value.SongId)) return;
        if (!RunAssignment.TryRestorePending(new[] { song.Value.SongId }, out _))
            Debug.LogWarning("[MatchResultController] Replay Song: the pending assignment could not be restored — replaying with the current session setup.");
    }

    private void OnMainMenuClicked()
    {
        FightMusicController.Instance?.Stop();
        AppBootstrap.Context?.AppFlow.RequestState(GameFlowState.MainMenu);
    }

    private void ShowRewardAdModal()
    {
        if (_rewardAdModalRoot != null) _rewardAdModalRoot.SetActive(true);
    }

    private void HideRewardAdModal()
    {
        if (_rewardAdModalRoot != null) _rewardAdModalRoot.SetActive(false);
    }

    private void OnWatchAdClicked()
    {
        _adService.ShowRewardedAd(success =>
        {
            HideRewardAdModal();
            if (!success)
            {
                Debug.Log("[MatchResultController] Rewarded Ad not granted — staying on Match Lost.");
                return;
            }

            // "+1 retry/life -> consumeix-la / inicia Fight Again" — granted and immediately spent,
            // see this phase's own explicit Rewarded Ad flow requirement.
            PlayerProgressService.Instance?.AddLife(1, "rewarded ad");
            BeginFightAgain();
        });
    }

    private void OnCancelAdClicked() => HideRewardAdModal();
