using System.Collections;
using TMPro;
using UnityEngine;
using UnityEngine.UI;

/// <summary>
/// Full-screen opaque overlay — shows itself the INSTANT GameFlowState.SongAnalysis is entered
/// (not only once PreAnalysisStartedEvent fires), since SongSelectionController now requests that
/// state immediately on Play, before a catalog song's Addressables clip has necessarily finished
/// loading (see SongAnalysisController) — the player must see "something is happening" the moment
/// they press Play, not after that load quietly finishes in the background.
///
/// The title shows the REAL preparation state of the current selection (SongPreparationEvent): downloading
/// (with its size) / loading / preparing for a published catalog song, analysing for an imported file.
/// For a catalog song the fill shows the real downloaded fraction and reaches 100% only when the content
/// stage is really complete (ContentReady) — stages without a measurable fraction leave it where it is.
///
/// Real progress is the target. A one-second visual sweep prevents cached/catalog loads from
/// flashing straight from empty to full. Slower analyses track real progress without a final delay.
/// When the FINAL style is published (MusicStyleDetectedEvent — also when ThemeManager, subscribed
/// independently, starts swapping CurrentTheme) a fixed "Style detected: X!" caption replaces the
/// rotating tips for StyleFlashSeconds — a presentation beat of the reveal, not progress — after
/// which MusicStyleRevealFinishedEvent lets SongAnalysisController continue to the Runner.
///
/// Stays up even AFTER GameFlowState leaves SongAnalysis for Gameplay — hiding right then would
/// reveal Runner's Mode Scene still being loaded/built (SceneFlowController's load is async, and
/// GameplayManager/MusicWorldManager/CameraFollow all still need to generate the level and hard-
/// snap the camera into position), which is exactly the camera "jump" this was covering up before.
/// The real Hide() trigger for that path is GameStartedEvent — GameplayManager only publishes it
/// once the level is generated AND the player/camera are already placed (see its own
/// GenerateAndStart) — so this overlay bridges the ENTIRE gap from "Play pressed" through "Runner
/// is fully ready", with the "3, 2, 1, GO" Countdown taking over the instant it's gone. The
/// failure path (a bad catalog load or a failed analysis bouncing back to Song Selection) still
/// hides immediately on leaving SongAnalysis, since there's no scene load to wait for there.
///
/// Presentation is delegated to AnalysisPresentation on the prefab: shared atlas, brush title,
/// song metadata and style crossfade. Progress and readiness events remain owned here.
///
/// Structure and look: AnalyzingScreen.prefab (UIPrefabLibrarySO.analyzingScreen, generated by
/// Tools > MusicGame > UI > Build All UI Prefabs), instantiated under the root canvas in Awake — a
/// missing prefab is logged and this controller disables itself (no procedural fallback).
///
/// All shown text is looked up via Loc.Get (see its own doc) — nothing user-facing is hardcoded
/// here, so adding a language later is a translation-only change in the "UIText" table.
/// </summary>
public class AnalyzingScreenController : MonoBehaviour
{
    private const string TitleKey = "Analyzing.Title";

    private static readonly string[] TipKeys =
    {
        "Analyzing.Tip01", "Analyzing.Tip02", "Analyzing.Tip03", "Analyzing.Tip04",
        "Analyzing.Tip05", "Analyzing.Tip06", "Analyzing.Tip07", "Analyzing.Tip08",
        "Analyzing.Tip09", "Analyzing.Tip10", "Analyzing.Tip11", "Analyzing.Tip12",
    };

    [Tooltip("Tip line changes every random(minTipInterval, maxTipInterval) seconds while shown.")]
    [SerializeField] private float minTipInterval = 1f;
    [SerializeField] private float maxTipInterval = 2f;

    // How long the "Style detected: X!" caption is held before the reveal counts as finished.
    private const float StyleFlashSeconds = 2.1f;

    private RectTransform _root;
    private TextMeshProUGUI _titleText;
    private TextMeshProUGUI _tipText;
    private Image _progressFill;

    private Coroutine _tipRoutine;
    private Coroutine _revealRoutine;
    private int       _lastTipIndex = -1;
    private float     _lastProgress;
    private float     _shownAt;
    private const float QuickLoadSweepSeconds = 1f;

    private System.Action<GameFlowStateChangedEvent> _onFlowStateChanged;
    private System.Action<PreAnalysisProgressEvent>  _onProgress;
    private System.Action<MusicStyleDetectedEvent>   _onStyleDetected;
    private System.Action<GameStartedEvent>          _onGameStarted;
    private System.Action<SongPreparationEvent>      _onPreparation;

    private AnalyzingScreenView _view;
    private AnalysisPresentation _presentation;
    private bool _pendingNextSelection;
    private bool _handoffDone;
    private Transform _raisedHud;
    private int _hudSibling;
    private CanvasGroup _hudGroup;
    private float _hudOriginalAlpha;

    /// <summary>Reveal the actual HUD over the cover before starting the music clock/countdown.</summary>
    public IEnumerator PrepareGameplayHandoff()
    {
        if (_root == null || !_root.gameObject.activeInHierarchy || _presentation == null || _handoffDone) yield break;
        var hud = FindFirstObjectByType<LiveHudView>();
        if (hud == null || !DetectedStyleLabel.HasDestination) yield break;
        _raisedHud = hud.transform; _hudSibling = _raisedHud.GetSiblingIndex();
        _raisedHud.SetAsLastSibling();
        _hudGroup = hud.GetComponent<CanvasGroup>();
        if (_hudGroup == null) _hudGroup = hud.gameObject.AddComponent<CanvasGroup>();
        _hudOriginalAlpha = _hudGroup.alpha; _hudGroup.alpha = 0;
        Canvas.ForceUpdateCanvases(); DetectedStyleLabel.Dock();
        float started = Time.unscaledTime;
        while (_root.gameObject.activeInHierarchy && (Time.unscaledTime - started < 1f || !DetectedStyleLabel.IsDocked))
        {
            float elapsed = Time.unscaledTime - started;
            if (elapsed > 1.8f) break; // Missing/destroyed HUD cannot block a ready run.
            _hudGroup.alpha = _hudOriginalAlpha * Mathf.SmoothStep(0, 1, Mathf.Clamp01(elapsed / .25f));
            _presentation.SetHandoffProgress(elapsed);
            yield return null;
        }
        if (_hudGroup != null) _hudGroup.alpha = _hudOriginalAlpha;
        _handoffDone = true;
    }
    private void RestoreHudOrder()
    {
        if (_raisedHud != null) _raisedHud.SetSiblingIndex(_hudSibling);
        if (_hudGroup != null) _hudGroup.alpha = _hudOriginalAlpha;
        _raisedHud = null; _hudGroup = null;
    }

    /// <summary>Same preparation screen while the next catalog identity is being selected.</summary>
    public void ShowPendingNextSong()
    {
        Show(); _pendingNextSelection = true;
        if (_presentation != null) _presentation.BeginPendingSelection();
        _stageTipKey = "Preparing.Preparing";
        if (_tipText != null) Loc.Set(_tipText, _stageTipKey);
    }

    private void Awake()
    {
        var lib = UIPrefabLibrarySO.Instance;
        _view = UIPrefabLibrarySO.Spawn(lib != null ? lib.analyzingScreen : null, UIFactory.RootCanvas(), "AnalyzingScreen");
        if (_view == null) { enabled = false; return; }
        WireUI(_view);
    }

    private void OnDestroy()
    {
        if (_view != null) Destroy(_view.gameObject);
    }

    private void OnEnable()
    {
        _onFlowStateChanged = e =>
        {
            if (e.Current == GameFlowState.SongAnalysis) Show();
            else if (_pendingNextSelection && e.Current != GameFlowState.Fight) Hide();
            // Only the FAILURE path (bounced back to Song Selection — see
            // SongSelectionController.OnPlayClicked / SongAnalysisController.OnAnalysisFailed) hides
            // here. The success path (→ Gameplay) deliberately does NOT hide on this transition —
            // Runner's Mode Scene has only just started loading at this point (SceneFlowController.
            // LoadMode is async), and GameplayManager/MusicWorldManager/CameraFollow all still need to
            // build the level and hard-snap the camera into position afterward. GameStartedEvent
            // (below) is the real "Runner is fully ready" signal.
            else if (e.Previous == GameFlowState.SongAnalysis && e.Current != GameFlowState.Gameplay) Hide();
        };
        _onProgress = e => SetFill(e.Progress);
        _onStyleDetected = e => { if (!_pendingNextSelection && _root != null && _root.gameObject.activeSelf) ShowStyleDetected(e.GameStyle); };
        _onGameStarted = _ => Hide(true);
        _onPreparation = e =>
        {
            if (GameSession.Instance != null && e.SelectionGeneration != GameSession.Instance.SelectionGeneration) return; // stale
            if (_root == null || !_root.gameObject.activeSelf) return;
            ApplyStage(e.Stage, e.DownloadBytes);
            if (e.Stage == SongPreparationStage.Downloading && e.Progress >= 0f) SetFill(e.Progress);
            else if (e.Stage == SongPreparationStage.ContentReady) SetFill(1f);
        };
        EventBus.Subscribe(_onPreparation);
        EventBus.Subscribe(_onFlowStateChanged);
        EventBus.Subscribe(_onProgress);
        EventBus.Subscribe(_onStyleDetected);
        EventBus.Subscribe(_onGameStarted);

        // Same UI-Scene-loads-asynchronously race as the other Frontend screens.
        if (AppBootstrap.Context != null && AppBootstrap.Context.AppFlow.CurrentState == GameFlowState.SongAnalysis)
            Show();
    }

    private void OnDisable()
    {
        RestoreHudOrder();
        EventBus.Unsubscribe(_onFlowStateChanged);
        EventBus.Unsubscribe(_onProgress);
        EventBus.Unsubscribe(_onStyleDetected);
        EventBus.Unsubscribe(_onGameStarted);
        EventBus.Unsubscribe(_onPreparation);
    }

    private void SetFill(float value)
    {
        _lastProgress = Mathf.Max(_lastProgress, Mathf.Clamp01(value));

    }

    private void Update()
    {
        if (_root == null || !_root.gameObject.activeSelf || _progressFill == null) return;
        float sweep = Mathf.Clamp01((Time.unscaledTime - _shownAt) / QuickLoadSweepSeconds);
        // Never run ahead of real work. After the first second this is exactly the real progress.
        _progressFill.fillAmount = Mathf.Min(_lastProgress, sweep);
    }

    private string _stageTipKey;
    private string _downloadSize;
    private void ApplyStage(SongPreparationStage stage, long downloadBytes)
    {
        if (_titleText != null) Loc.Set(_titleText, TitleKey);
        _downloadSize=(downloadBytes/1048576f).ToString("0.0");
        _stageTipKey=stage switch
        {
            SongPreparationStage.Downloading => "Preparing.Downloading",
            SongPreparationStage.ResolvingSelection or SongPreparationStage.LoadingContent or
            SongPreparationStage.ValidatingProfile or SongPreparationStage.BuildingProfile or
            SongPreparationStage.PreparingAudio or SongPreparationStage.ContentReady => "Preparing.Loading",
            SongPreparationStage.ResolvingStyle or SongPreparationStage.ApplyingTheme or
            SongPreparationStage.LoadingScene or SongPreparationStage.PreparingWorld or
            SongPreparationStage.PreparingConsumers or SongPreparationStage.Ready => "Preparing.Preparing",
            _ => null
        };
        if(_tipText!=null && _stageTipKey!=null)Loc.Set(_tipText,_stageTipKey,_downloadSize);
    }

    // ── Prefab wiring — see AnalyzingScreenView's own doc ────────────────────────

    private void WireUI(AnalyzingScreenView view)
    {
        _root = (RectTransform)view.transform;
        UIFactory.Stretch(_root);
        _root.SetAsLastSibling(); // always drawn above whatever other UI exists so far
        _titleText    = view.titleText;
        _tipText      = view.tipText;
        _progressFill = UIFactory.EnsureFillSprite(view.progressFill);

        _presentation = view.GetComponent<AnalysisPresentation>();
        if (_presentation != null) _presentation.Build(view);
        _root.gameObject.SetActive(false);
    }

    // ── Show / hide ─────────────────────────────────────────────────────────────

    private void Show()
    {
        RestoreHudOrder(); _handoffDone = false;
        _pendingNextSelection = false;
        _stageTipKey = null;
        _shownAt = Time.unscaledTime;
        _root.gameObject.SetActive(true);
        _root.SetAsLastSibling();
        if (_presentation != null) _presentation.Begin();
        Loc.Set(_titleText, TitleKey);
        if (_progressFill != null) _progressFill.fillAmount = 0f;
        // The preparation may already have reported a state for this selection (event order is not guaranteed).
        if (GameSession.Instance != null && SongPreparation.CurrentGeneration == GameSession.Instance.SelectionGeneration)
            ApplyStage(SongPreparation.Current, 0);

        _lastProgress = 0f;
        StopRoutines();
        _lastTipIndex = -1;
        _tipRoutine = StartCoroutine(RotateTips());
    }

    private void Hide(bool dockStyle = false)
    {
        _pendingNextSelection = false;
        if (dockStyle) { if (!_handoffDone) DetectedStyleLabel.Dock(); }
        else DetectedStyleLabel.Cancel();
        RestoreHudOrder();
        if (_root != null) _root.gameObject.SetActive(false);
        StopRoutines();
    }

    private void StopRoutines()
    {
        if (_tipRoutine != null)    { StopCoroutine(_tipRoutine);    _tipRoutine    = null; }
        if (_revealRoutine != null) { StopCoroutine(_revealRoutine); _revealRoutine = null; }
    }

    // The final style is known: hold its caption while real progress / the quick-load sweep continues.
    private void ShowStyleDetected(GameMusicStyle style)
    {
        StopRoutines();
        _revealRoutine = StartCoroutine(RevealAtSweepMidpoint(style));
    }

    private IEnumerator RevealAtSweepMidpoint(GameMusicStyle style)
    {
        // Cache/catalog detections wait for the midpoint of the very same visual sweep.
        // A real analysis that has already passed it incurs no additional delay.
        float revealAt = _shownAt + QuickLoadSweepSeconds * .5f;
        while (Time.unscaledTime < revealAt) yield return null;
        if (_presentation != null) _presentation.Reveal(style);
        if (_tipText != null) Loc.Set(_tipText, "Preparing.Preparing");
        yield return AfterStyleFlash();
    }

    private IEnumerator AfterStyleFlash()
    {
        yield return new WaitForSecondsRealtime(StyleFlashSeconds);

        // A fast ready result must finish its short sweep before releasing the presentation gate.
        while (_lastProgress >= 1f && _progressFill != null && _progressFill.fillAmount < 1f)
            yield return null;

        // The final style has been shown — SongAnalysisController may continue to the Runner now.
        _revealRoutine = null;
        EventBus.Publish(new MusicStyleRevealFinishedEvent());

        // Still analysing (early, tags-only style): back to the rotating tips while it finishes.
        if (_lastProgress < 1f)
        {
            _lastTipIndex = -1;
            _tipRoutine = StartCoroutine(RotateTips());
        }
    }

    private IEnumerator RotateTips()
    {
        while (true)
        {
            if(_stageTipKey!=null)Loc.Set(_tipText,_stageTipKey,_downloadSize);
            else Loc.Set(_tipText, "Preparing.Preparing");
            yield return new WaitForSeconds(Random.Range(minTipInterval, maxTipInterval));
        }
    }

    // Never repeats the immediately-previous tip (as long as there's more than one to pick from).
    private string NextTipKey()
    {
        int idx;
        do { idx = Random.Range(0, TipKeys.Length); } while (TipKeys.Length > 1 && idx == _lastTipIndex);
        _lastTipIndex = idx;
        return TipKeys[idx];
    }
}
