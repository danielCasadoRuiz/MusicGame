using System.Collections;
using System.Collections.Generic;
using TMPro;
using UnityEngine;
using UnityEngine.AddressableAssets;
using UnityEngine.ResourceManagement.AsyncOperations;
using UnityEngine.ResourceManagement.ResourceLocations;
using UnityEngine.UI;

/// <summary>
/// Song Selection screen — lists every audio clip tagged with the "Song" Addressables label (see
/// SongAddressablesSetup — no hand-authored catalog ScriptableObject any more: dropping a new clip
/// into Assets/_Project/Audio/Music and re-running that tool is the whole "add a song" workflow, and
/// removing one is the same in reverse), "PLAY YOUR SONG" (local file, via the existing
/// ILocalSongPicker abstraction), and three disabled placeholder streaming buttons (Spotify/YouTube
/// Music/Amazon Music — Section 9 of the multi-scene refactor plan: no real APIs yet, just a clear
/// "Coming Soon" seam for later).
///
/// IMPORTANT (Section 9): selecting a row or picking a local file only records/highlights the
/// selection — it never starts anything by itself. A separate PLAY button is what actually writes
/// GameSession.SelectedSong and advances the flow to GameFlowState.SongAnalysis.
///
/// Mostly a pure SCREEN CONTROLLER — static children (title, dim, buttons) carry generic receivers
/// (ThemeColorReceiver/ThemeTextReceiver). The one exception is the song-row SELECTION highlight:
/// which row is tinted depends on INTERACTION state (which row is currently selected), not just the
/// theme, so a generic receiver can't express it — this class keeps that one piece directly and
/// re-applies it on ThemeChangedEvent too, so the highlight's accent color never goes stale after a
/// Theme swap.
///
/// Structure and look: Prefabs/UI/SongSelection.prefab (SongSelectionView, UIPrefabLibrarySO.songSelection)
/// for the static chrome, and one Prefabs/UI/Items/SongRow.prefab (SongRowView, UIPrefabLibrarySO.songRow)
/// per catalog entry, spawned into the view's songListRoot once the Addressables query resolves. Both are
/// generated by FrontendScreenPrefabs and edited by hand; no UI is built in code — a missing prefab is
/// logged and the screen stays disabled (or the list stays empty).
///
/// Lives in the always-loaded UI Scene (added by UIFlowController) — reacts to
/// GameFlowStateChangedEvent directly, same pattern as the other Frontend screens. Never touches an
/// AudioSource itself: RunnerSceneBootstrap already re-applies GameSession.SelectedSong.Clip onto
/// its own local AudioSource right before starting analysis, so this screen only ever needs to set
/// GameSession.SelectedSong — no cross-scene AudioSource reference required.
/// </summary>
public class SongSelectionController : MonoBehaviour
{
    // Styling read from SongSelectionView (editable in the prefab); defaults match the view's own.
    private Color _neutralStatusColor = new(0.75f, 0.75f, 0.75f);
    private Color _errorStatusColor   = new(0.85f, 0.35f, 0.3f);
    private Color _rowUnselectedColor = new(1f, 1f, 1f, 0.12f);
    private float _rowSelectedAlpha = 0.35f;
    private Color _fallbackAccentColor = new(0.18f, 0.75f, 0.95f);

    private SongSelectionView _view;
    private RectTransform _root;
    private RectTransform _songListRoot;
    private TextMeshProUGUI _playButtonLabel;
    private Button _playButton;
    private TextMeshProUGUI _statusText;

    private const string SongLabel = "Song";

    private readonly List<IResourceLocation> _entries = new();
    private SongSelectionService _service;

    private readonly List<Image> _rowBackgrounds = new(); // catalog rows only — see _localFileRowBackground
    private Image _localFileRowBackground; // "Play Your Song" — a standalone button, not part of the list
    private int _selectedCatalogIndex = -1;
    private SelectedSongInfo? _selectedLocalInfo;
    private bool _isLoading;

    private System.Action<GameFlowStateChangedEvent> _onFlowStateChanged;
    private System.Action<ThemeChangedEvent> _onThemeChanged;
    private System.Action<SongPreparationEvent> _onPreparation;

    private void Awake()
    {
        _service = gameObject.AddComponent<SongSelectionService>();

        var lib = UIPrefabLibrarySO.Instance;
        _view = UIPrefabLibrarySO.Spawn(lib != null ? lib.songSelection : null, UIFactory.RootCanvas(), "SongSelection");
        if (_view == null) { enabled = false; return; }
        WireUI(_view);

        StartCoroutine(LoadCatalogAndPopulate());
    }

    private void OnDestroy()
    {
        if (_view != null) Destroy(_view.gameObject);
    }

    private void OnEnable()
    {
        _onFlowStateChanged = e =>
        {
            if (e.Current == GameFlowState.SongSelection)
            {
                // Only the Match Result's SELECT SONG (from Fight) keeps BACK pointed at the result.
                if (e.Previous != GameFlowState.Fight) MatchResultReturn.Disarm();
                Show();
            }
            else if (e.Previous == GameFlowState.SongSelection) Hide();
        };
        EventBus.Subscribe(_onFlowStateChanged);

        // The row-selection highlight is interaction state, not pure theming, so it isn't a generic
        // receiver — but its color IS a theme token, so it still needs to react when Theme changes
        // (Section 15: never go stale) — a plain re-tint, no interpolation needed for this secondary
        // highlight refresh.
        _onThemeChanged = _ => RefreshRowHighlight(CurrentAccentColor());
        EventBus.Subscribe(_onThemeChanged);

        // A failed preparation comes back here: show WHY (each reason has its own recovery — retry with
        // PLAY for network / load problems, a content update for incompatible content).
        _onPreparation = e =>
        {
            if (e.Stage != SongPreparationStage.Failed || e.Error == SongContentError.Cancelled) return;
            _isLoading = false;
            RefreshPlayButtonInteractable();
            SetStatus(Loc.Get(FailureKey(e.Error)), _errorStatusColor);
        };
        EventBus.Subscribe(_onPreparation);

        // Same UI-Scene-loads-asynchronously race as the other Frontend screens.
        if (AppBootstrap.Context != null && AppBootstrap.Context.AppFlow.CurrentState == GameFlowState.SongSelection)
            Show();
    }

    private void OnDisable()
    {
        EventBus.Unsubscribe(_onFlowStateChanged);
        EventBus.Unsubscribe(_onThemeChanged);
        EventBus.Unsubscribe(_onPreparation);
    }

    private static string FailureKey(SongContentError error) => error switch
    {
        SongContentError.DownloadFailed      => "SongSelection.DownloadFailed",
        SongContentError.IndexUnavailable    => "SongSelection.DownloadFailed",
        SongContentError.IncompatibleContent => "SongSelection.ContentIncompatible",
        _                                    => "SongSelection.LoadFailed",
    };

    // ── Prefab wiring — see SongSelectionView's own doc ──────────────────────────

    private void WireUI(SongSelectionView view)
    {
        _root            = view.root.GetComponent<RectTransform>();
        UIFactory.Stretch(_root);
        _root.SetAsLastSibling();
        _songListRoot    = view.songListRoot;
        _playButton      = view.playButton;
        _playButtonLabel = view.playButtonLabel;
        _statusText      = view.statusText;
        // Deliberately NOT a ThemeColorReceiver — its color depends on selection state (see
        // RefreshRowHighlight), not just the theme, same reasoning as the catalog rows.
        _localFileRowBackground = view.playYourSongButton.GetComponent<Image>();

        _neutralStatusColor   = view.neutralStatusColor;
        _errorStatusColor     = view.errorStatusColor;
        _rowUnselectedColor  = view.rowUnselectedColor;
        _rowSelectedAlpha    = view.rowSelectedAlpha;
        _fallbackAccentColor = view.fallbackAccentColor;

        view.backButton.onClick.AddListener(() => { StopPreview(); MatchResultReturn.Back(); }); // result it came from, else Main Menu
        view.playButton.onClick.AddListener(OnPlayClicked);
        view.playYourSongButton.onClick.AddListener(OnPlayYourSongClicked);

        // Static captions are LocalizedText in the prefab; the streaming ones are composite (service +
        // "Coming Soon"), so they stay bound here.
        Loc.Bind(view.spotifyLabel, () => ComingSoonLabel("SongSelection.Spotify"));
        Loc.Bind(view.youtubeMusicLabel, () => ComingSoonLabel("SongSelection.YouTubeMusic"));
        Loc.Bind(view.amazonMusicLabel, () => ComingSoonLabel("SongSelection.AmazonMusic"));
        _statusText.text = "";
        _statusText.color = _neutralStatusColor;

        _root.gameObject.SetActive(false);
    }

    // Queries every asset tagged with the "Song" Addressables label — this IS the catalog now,
    // there is no hand-authored list to fall back to. Resolves near-instantly (it's a local catalog
    // lookup, not a real download) — the screen is still hidden at this point in virtually every
    // real case (reaching SongSelection requires the player to get through Intro/MainMenu first),
    // so the brief async gap is never actually visible.
    private IEnumerator LoadCatalogAndPopulate()
    {
        // After the startup catalog check + the published index (SongCatalogService): a song added by a
        // content update is listed with its stable id; a location nobody published an id for is skipped.
        yield return SongCatalogService.EnsureReady();
        AsyncOperationHandle<IList<IResourceLocation>> handle =
            Addressables.LoadResourceLocationsAsync(SongLabel, typeof(AudioClip));
        yield return handle;

        _entries.Clear();
        if (handle.Status == AsyncOperationStatus.Succeeded)
        {
            foreach (var location in handle.Result)
                if (SongProgression.IdOf(location) != null) _entries.Add(location);
                else Debug.LogWarning($"[SongSelectionController] '{location.PrimaryKey}' has no published songId — not listed.");
        }
        else
            Debug.LogWarning("[SongSelectionController] Failed to query the 'Song' Addressables label.");
        Addressables.Release(handle);

        PopulateSongRows();
        RefreshPlayButtonInteractable();
    }

    // Spawns one SongRow prefab per catalog entry, in the order Addressables returned them — never
    // called more than once per screen lifetime (this controller doesn't support the catalog changing
    // while the screen is already up). _songListRoot is a VerticalLayoutGroup's Content transform in
    // SongSelection.prefab — rows keep their own prefab height; the layout group handles
    // stacking/width/scrolling. "PLAY YOUR SONG" is NOT one of these rows — it is a standalone button
    // outside the scrollable list.
    private void PopulateSongRows()
    {
        var lib = UIPrefabLibrarySO.Instance;
        for (int i = 0; i < _entries.Count; i++)
        {
            int index = i; // capture
            var location = _entries[i];

            var row = UIPrefabLibrarySO.Spawn(lib != null ? lib.songRow : null, _songListRoot, "SongRow");
            if (row == null) break; // missing prefab: logged by Spawn
            row.name = "SongRow_" + i;
            row.label.text = SongCatalog.DisplayNameForAddress(location.PrimaryKey); // published display name (the address is the ASCII songId key)

            // Row BACKGROUND is deliberately NOT a ThemeColorReceiver — its color depends on
            // selection state (see RefreshRowHighlight), not just the theme.
            _rowBackgrounds.Add(row.background);
            row.button.onClick.AddListener(() => SelectCatalogSong(index));
            _rowButtons.Add(row.button);
            _rowLabels.Add(row.label);

            // Play/Pause on the card itself — selects the song too (see OnCardPlayPause).
            Loc.Set(row.playPauseLabel, "SongSelection.CardPlay");
            row.playPauseButton.onClick.AddListener(() => OnCardPlayPause(index));
            _cardPlayButtons.Add(row.playPauseButton);

            // Played check (history) — its own column between the name and PREVIEW (see RefreshCompletedRows).
            _rows.Add(row);
            _cardPlayLabels.Add(row.playPauseLabel);
        }
        RefreshCompletedRows();
        RefreshPreviewButton();
    }

    // ── Row state: played history (check) vs use in THIS lap (selection) — two independent things ──────

    private readonly List<Button> _rowButtons = new();
    private readonly List<Button> _cardPlayButtons = new();
    private readonly List<TextMeshProUGUI> _rowLabels = new();
    private readonly List<SongRowView> _rows = new();

    // Unavailable = already used (won) in THIS lap — the only thing that blocks selection. The check is the
    // all-time played history (any lap, won or not): shown, never consulted for availability.
    private bool IsCompletedRow(int index) =>
        index >= 0 && index < _entries.Count && SongProgression.IsUsedThisLap(SongProgression.IdOf(_entries[index]));
    private bool IsPlayedRow(int index) =>
        index >= 0 && index < _entries.Count && SongProgression.IsPlayed(SongProgression.IdOf(_entries[index]));

    /// <summary>Every song stays in the list. The check is on once the song was ever played (dim otherwise); a song
    /// used in this lap gets the disabled row style (dimmed name, row + PREVIEW not interactable). Re-run on every Show.</summary>
    private void RefreshCompletedRows()
    {
        SongProgression.RefreshLapUse(SongProgression.Ids(_entries));
        for (int i = 0; i < _rowButtons.Count && i < _entries.Count; i++)
        {
            bool done = IsCompletedRow(i);
            _rows[i].SetPlayed(done || IsPlayedRow(i));
            _rowButtons[i].interactable = !done;
            // PREVIEW keeps its place (no layout jump); as before, a song used in this lap is not previewed.
            _cardPlayButtons[i].interactable = !done;
            string name = SongCatalog.DisplayNameForAddress(_entries[i].PrimaryKey);
            _rowLabels[i].text = done ? $"<alpha=#66>{name}" : name;
        }
        if (IsCompletedRow(_selectedCatalogIndex)) { StopPreview(); _selectedCatalogIndex = -1; }
        RefreshRowHighlight(CurrentAccentColor());
        RefreshPlayButtonInteractable();
    }

    // ── Preview (SongPreviewPlayer — one preview at a time, per-song range in SongPreviewConfigSO) ──

    // One authoritative state: the selected song (_selectedCatalogIndex) + SongPreviewPlayer's single
    // playing preview. Cards only reflect it.
    private readonly List<TMPro.TextMeshProUGUI> _cardPlayLabels = new();

    /// <summary>Card Play/Pause: PLAY selects that song (stopping any other preview) and starts its
    /// preview; PAUSE on the playing card stops it. Only one song selected, one preview playing.</summary>
    private void OnCardPlayPause(int index)
    {
        var player = SongPreviewPlayer.Instance;
        if (player == null || index < 0 || index >= _entries.Count || IsCompletedRow(index)) return;
        var location = _entries[index];
        if (player.IsPlaying && player.PlayingId == location.PrimaryKey) { player.Stop(); return; }
        SelectCatalogSong(index); // stops the previous preview when the selection changes
        player.Play(location);
    }

    private void StopPreview() => SongPreviewPlayer.Instance?.Stop();

    private void RefreshPreviewButton()
    {
        var player = SongPreviewPlayer.Instance;
        string playingId = player != null && player.IsPlaying ? player.PlayingId : null;
        for (int i = 0; i < _cardPlayLabels.Count && i < _entries.Count; i++)
            if (_cardPlayLabels[i] != null)
                Loc.Set(_cardPlayLabels[i], playingId == _entries[i].PrimaryKey ? "SongSelection.CardPause" : "SongSelection.CardPlay");

        // Lightweight range readout in the existing status line while a preview plays.
        bool showing = playingId != null && player.PlayingRange.duration > 0f;
        if (showing)
        {
            var (start, duration) = player.PlayingRange;
            SetStatus(Loc.Get("SongSelection.PreviewRange", Clock(start), Clock(start + duration)), _neutralStatusColor);
        }
        else if (_statusText != null && _previewRangeShown) SetStatus(null);
        _previewRangeShown = showing;
    }

    private bool _previewRangeShown;
    private static string Clock(float seconds)
    {
        int s = Mathf.Max(0, Mathf.RoundToInt(seconds));
        return $"{s / 60:00}:{s % 60:00}";
    }

    // ── Show / hide ─────────────────────────────────────────────────────────────

    private void Show()
    {
        _root.gameObject.SetActive(true);
        _root.SetAsLastSibling();
        RefreshCompletedRows();
        RefreshPlayButtonInteractable();
        if (SongPreviewPlayer.Instance != null)
        {
            SongPreviewPlayer.Instance.StateChanged -= RefreshPreviewButton;
            SongPreviewPlayer.Instance.StateChanged += RefreshPreviewButton;
        }
        RefreshPreviewButton();
    }

    private void Hide()
    {
        StopPreview(); // leaving the selector never leaves a preview playing
        if (_root != null) _root.gameObject.SetActive(false);
    }

    // ── Selection ───────────────────────────────────────────────────────────────

    private void SelectCatalogSong(int index)
    {
        if (IsCompletedRow(index)) return; // completed songs are not selectable for normal progression
        if (index != _selectedCatalogIndex) StopPreview(); // a different song: the old preview stops
        _selectedCatalogIndex = index;
        _selectedLocalInfo = null;
        RefreshRowHighlight(CurrentAccentColor());
        RefreshPlayButtonInteractable();
        RefreshPreviewButton();
        SetStatus(null);
    }

    private void OnPlayYourSongClicked()
    {
        var source = new LocalFileSongSource(LocalSongPickerFactory.Create());
        StartCoroutine(source.Load(info =>
        {
            if (info == null)
            {
                SetStatus(Loc.Get("SongSelection.LocalFileCancelled"), _errorStatusColor);
                return;
            }
            StopPreview();
            _selectedLocalInfo = info;
            _selectedCatalogIndex = -1;
            RefreshPreviewButton();
            RefreshRowHighlight(CurrentAccentColor());
            RefreshPlayButtonInteractable();
            SetStatus(Loc.Get("SongSelection.LocalFileSelected", info.Value.DisplayName), _neutralStatusColor);
        }));
    }

    private void RefreshRowHighlight(Color accent)
    {
        var selectedColor   = new Color(accent.r, accent.g, accent.b, _rowSelectedAlpha);
        var unselectedColor = _rowUnselectedColor;

        for (int i = 0; i < _rowBackgrounds.Count; i++)
            _rowBackgrounds[i].color = i == _selectedCatalogIndex ? selectedColor : unselectedColor;

        if (_localFileRowBackground != null)
            _localFileRowBackground.color = _selectedLocalInfo.HasValue ? selectedColor : unselectedColor;
    }

    private Color CurrentAccentColor() =>
        ThemeManager.Instance != null && ThemeManager.Instance.CurrentTheme != null && ThemeManager.Instance.CurrentTheme.UI != null
            ? ThemeManager.Instance.CurrentTheme.UI.accentColor
            : _fallbackAccentColor;

    private bool HasSelection => _selectedCatalogIndex >= 0 || _selectedLocalInfo.HasValue;

    private void RefreshPlayButtonInteractable()
    {
        if (_playButton != null) _playButton.interactable = HasSelection && !_isLoading;
    }

    private static string ComingSoonLabel(string serviceKey) => Loc.Get(serviceKey) + " (" + Loc.Get("SongSelection.ComingSoon") + ")";

    private void SetStatus(string text, Color? color = null)
    {
        if (_statusText == null) return;
        _statusText.text  = text ?? "";
        _statusText.color = color ?? _neutralStatusColor;
    }

    // ── PLAY (the only thing that actually advances the flow) ───────────────────

    private void OnPlayClicked()
    {
        if (!HasSelection || _isLoading) return;
        StopPreview(); // the real run starts — never alongside a preview
        MatchResultReturn.Disarm(); // a new song is played: the result screen is left for good
        if (!_selectedLocalInfo.HasValue) CampaignService.MarkFirstSongChosen(); // the new lap's first song is chosen

        if (_selectedLocalInfo.HasValue)
        {
            if (GameSession.Instance != null) GameSession.Instance.SelectedSong = _selectedLocalInfo;
            RunAssignment.AssignSessionOnly(); // rival decided now; nothing persisted, catalog pendingRun untouched
            AppBootstrap.Context?.AppFlow.RequestState(GameFlowState.SongAnalysis);
            return;
        }

        // The NEW selection is recorded FIRST and only then SongAnalysis is entered (same order as Main Menu
        // CONTINUE / Next Song): a catalog selection loads nothing (CatalogSongSource completes in the same
        // frame — the readiness barrier downloads/loads on the Analyzing screen), so the screen still appears
        // the instant Play is pressed, and the preparation never starts on the previous song.
        _isLoading = true;
        RefreshPlayButtonInteractable();

        var location = _entries[_selectedCatalogIndex];
        // A manual choice is the player's new preference: future CONTINUE follows songs similar to it.
        // CONFIRMING it (not merely opening the selector) replaces an unfinished assignment — the
        // abandoned song is NOT completed. Re-confirming the pending song itself keeps its rival.
        var catalogIds = SongProgression.Ids(_entries);
        string songId = SongProgression.IdOf(location); // stable id; the address is only how it loads
        SongProgression.OnManualSelection(songId, catalogIds);
        var pending = PlayerProgressService.Instance != null ? PlayerProgressService.Instance.PendingRun : null;
        if (pending == null || pending.songId != songId || !RunAssignment.TryRestorePending(catalogIds, out _))
            RunAssignment.CreatePendingRun(songId);
        StartCoroutine(_service.SelectSong(new CatalogSongSource(songId, SongCatalog.DisplayNameFor(songId)), null, success =>
        {
            _isLoading = false;
            if (!success)
            {
                // Nothing selected: stay on Song Selection (it was never left) with the reason.
                RefreshPlayButtonInteractable();
                SetStatus(Loc.Get("SongSelection.LoadFailed"), _errorStatusColor);
                return;
            }
            AppBootstrap.Context?.AppFlow.RequestState(GameFlowState.SongAnalysis);
        }));
    }
}
